// Writes the SQL for better-auth's tables as the next file in migrations/.
// D1 can't be reached by `auth migrate`, so this loads the same options against an in-memory SQLite database that has
// the existing migrations applied, and saves only what is still missing. Run it after changing worker/options.ts.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';
import { getMigrations } from 'better-auth/db/migration';
import { buildOptions } from '../worker/options.ts';

const dir = new URL('../migrations/', import.meta.url);
const files = readdirSync(dir).filter((name) => name.endsWith('.sql')).sort();

const database = new DatabaseSync(':memory:');
for (const name of files) database.exec(readFileSync(new URL(name, dir), 'utf8'));

const options = buildOptions({
  database,
  baseURL: 'http://localhost',
  secret: 'schema-generation-only-not-a-real-secret',
  extraOrigins: [],
  signupAllow: [],
  sendEmail: async () => {},
  isInvited: async () => false,
  initialOrganizationId: async () => null,
  rememberOrganization: async () => {},
  removeResetTokens: async () => {},
  hasPassword: async () => false,
  promoteAdmin: async () => {},
  removeApiKeys: async () => {},
  ipHeaders: [],
});

const { toBeCreated, toBeAdded, compileMigrations } = await getMigrations(options);
if (!toBeCreated.length && !toBeAdded.length) {
  console.log('The migrations already match the better-auth options.');
} else {
  const next = String(files.length + 1).padStart(4, '0');
  const label = process.argv[2] ?? 'auth';
  const sql = (await compileMigrations()).replace(/;\s*/g, ';\n\n').trim();
  writeFileSync(new URL(`${next}_${label}.sql`, dir), `-- Generated by \`pnpm auth:schema\` from worker/options.ts (better-auth).\n\n${sql}\n`);
  console.log(`Wrote migrations/${next}_${label}.sql:`, [...toBeCreated, ...toBeAdded].map((change) => change.table).join(', '));
}
